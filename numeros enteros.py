
# Solicita dos números enteros al usuario y
# determina cuál es el mayor. Si son iguales,
# indica que son iguales. Usa estructuras
# condicionales.

n1=int(input("ingrese el primer numero : "))
n2=int(input("ingrese el segundo numero :"))

if n1>n2:
    print("El primer numero es mayor que el segundo numero ")
elif n1<n2:
    print("El segundo numero es mayor que el primer numero ")
else:
    print("Los dos numeros son iguales ")
    

